/** A tiny checksum/write helper for private application documents — deliberately separate from asset-writer.mjs's storeAsset(), since these never get a media_assets row or webp variants (PrivateFileStore.store(), src/storage/private-file-store.service.ts). */
async function writePrivateFile(applicationPredictedId, buffer, ext) {
  const dir = path.posix.join('private', 'applications', String(applicationPredictedId));
  const storageKey = path.posix.join(dir, `${randomUUID()}.${ext}`);
  await mkdir(path.join(STORAGE_ROOT, dir), { recursive: true });
  await writeFile(path.join(STORAGE_ROOT, storageKey), buffer);
  const detected = await fileTypeFromBuffer(buffer);
  const checksum = createHash('sha256').update(buffer).digest('hex');
  return { storageKey, mime: detected?.mime ?? 'application/octet-stream', sizeBytes: buffer.length, checksum };
}

