const orNull = (v) => (v === undefined || v === null || v === '' ? null : v);

/**
 * Runs the prototype's "shared copy" const block through vm and reads the
 * bindings off an explicit globalThis assignment — top-level `const` in a
 * vm-executed script creates a lexical binding, not an own property of the
 * sandbox object, so each name has to be attached by hand (same trick the
 * african_api reference tool uses for its own SEED object).
 */
function loadSharedCopy(html) {
  const startMarker = '/* ============================ shared copy ============================ */';
  const endMarker = '/* ============================ site chrome ============================ */';
  const start = html.indexOf(startMarker);
  const end = html.indexOf(endMarker);
  if (start === -1 || end === -1 || end <= start) {
    throw new Error('Could not find the shared-copy block markers in the prototype HTML');
  }
  const slice = html.slice(start + startMarker.length, end);

  const names = ['ORG', 'TAG', 'BLURB', 'PHONE', 'EMAIL', 'ADDR', 'RIGHTS', 'PLACEHOLDER', 'GOALS', 'AREAS', 'PILLARS', 'BOARD', 'EXEC', 'THEMES', 'NEWS1', 'NAV'];
  const exportLines = names.map((n) => `globalThis.__SEED_${n}__ = ${n};`).join('\n');

  const context = {};
  vm.createContext(context);
  vm.runInContext(slice + '\n' + exportLines, context);

  const out = {};
  for (const n of names) out[n] = context[`__SEED_${n}__`];
  return out;
}

/** `const LOGO_SRC = 'data:image/png;base64,...'` — one very long line, extracted with a regex against the raw text. */
function loadLogoSrc(html) {
  const m = html.match(/const LOGO_SRC = '(data:image\/png;base64,[^']+)'/);
  if (!m) throw new Error('Could not find LOGO_SRC in the prototype HTML');
  return m[1];
}

function loadPrototype() {
  if (!existsSync(PROTOTYPE_PATH)) {
    console.error(
      `Prototype HTML not found at ${PROTOTYPE_PATH}.\n` +
        'It is kept outside the repo. Set PROTOTYPE_PATH to its location (absolute, or relative to the repo root), e.g.\n' +
        '  PROTOTYPE_PATH=../../docs/safeer-prototype.html npm run seed',
    );
    process.exit(1);
  }
  const html = readFileSync(PROTOTYPE_PATH, 'utf8');
  const shared = loadSharedCopy(html);
  const logoSrc = loadLogoSrc(html);
  return { ...shared, LOGO_SRC: logoSrc };
}

